// Turns the agent mascot PNGs into SVG strings the pane can draw on any surface (no image decoding needed there).
// Usage: node build_icons.js <icons folder> [grid=32]
// Reads <folder>/<agent>.png (8-bit RGB or RGBA, not interlaced), averages blocks down to grid x grid,
// drops the #15171c background, merges horizontal runs into <rect>s and writes hooks/icons.ts.
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const dir = process.argv[2];
const GRID = parseInt(process.argv[3] || '32', 10);
if (!dir) throw new Error('usage: node build_icons.js <icons folder> [grid]');
const BG = [0x15, 0x17, 0x1c];
const BG_DIST = 36;

function decodePng(buf) {
  let pos = 8;
  let w = 0, h = 0, depth = 0, type = 0, interlace = 0;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos);
    const kind = buf.toString('ascii', pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if (kind === 'IHDR') { w = data.readUInt32BE(0); h = data.readUInt32BE(4); depth = data[8]; type = data[9]; interlace = data[12]; }
    if (kind === 'IDAT') idat.push(data);
    pos += 12 + len;
  }
  if (depth !== 8 || interlace !== 0 || (type !== 2 && type !== 6)) throw new Error(`unsupported PNG (depth ${depth}, type ${type}, interlace ${interlace})`);
  const bpp = type === 6 ? 4 : 3;
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = w * bpp;
  const out = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? out[y * stride + x - bpp] : 0;
      const b = y > 0 ? out[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? out[(y - 1) * stride + x - bpp] : 0;
      let v = line[x];
      if (f === 1) v += a;
      else if (f === 2) v += b;
      else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const p = a + b - c; const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      out[y * stride + x] = v & 255;
    }
  }
  return { w, h, bpp, px: out };
}

const q = v => Math.min(255, Math.round(v / 24) * 24);
const hex = (r, g, b) => '#' + [q(r), q(g), q(b)].map(v => v.toString(16).padStart(2, '0')).join('');

function toSvg(file) {
  const { w, h, bpp, px } = decodePng(fs.readFileSync(file));
  const cells = [];
  for (let gy = 0; gy < GRID; gy++) {
    const row = [];
    for (let gx = 0; gx < GRID; gx++) {
      const x0 = Math.floor((gx * w) / GRID), x1 = Math.max(x0 + 1, Math.floor(((gx + 1) * w) / GRID));
      const y0 = Math.floor((gy * h) / GRID), y1 = Math.max(y0 + 1, Math.floor(((gy + 1) * h) / GRID));
      let r = 0, g = 0, b = 0, n = 0;
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
        const i = (y * w + x) * bpp;
        if (bpp === 4 && px[i + 3] < 128) continue;
        r += px[i]; g += px[i + 1]; b += px[i + 2]; n++;
      }
      if (n < ((x1 - x0) * (y1 - y0)) / 2) { row.push(null); continue; }
      r = Math.round(r / n); g = Math.round(g / n); b = Math.round(b / n);
      const d = Math.hypot(r - BG[0], g - BG[1], b - BG[2]);
      row.push(d < BG_DIST ? null : hex(r, g, b));
    }
    cells.push(row);
  }
  const used = cells.map(r => r.map(() => false));
  const rects = [];
  for (let y = 0; y < GRID; y++) {
    for (let x = 0; x < GRID; x++) {
      const c = cells[y][x];
      if (!c || used[y][x]) continue;
      let w = 1;
      while (x + w < GRID && cells[y][x + w] === c && !used[y][x + w]) w++;
      let hgt = 1;
      while (y + hgt < GRID && Array.from({ length: w }, (_, i) => i).every(i => cells[y + hgt][x + i] === c && !used[y + hgt][x + i])) hgt++;
      for (let yy = y; yy < y + hgt; yy++) for (let xx = x; xx < x + w; xx++) used[yy][xx] = true;
      rects.push(`<rect x="${x}" y="${y}" width="${w}" height="${hgt}" fill="${c}"/>`);
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}" shape-rendering="crispEdges">${rects.join('')}</svg>`;
}

const names = fs.readdirSync(dir).filter(f => f.endsWith('.png')).map(f => f.replace(/\.png$/, '')).sort();
const lines = names.map(n => `  ${JSON.stringify(n)}: ${JSON.stringify(toSvg(path.join(dir, n + '.png')))},`);
const outFile = path.join(__dirname, 'hooks', 'icons.ts');
fs.writeFileSync(outFile, `// Pixel-art agent icons as SVG strings, generated by build_icons.js from ${names.length} PNGs. Do not edit.\nexport const ICON_SVG: Record<string, string> = {\n${lines.join('\n')}\n}\n`);
console.log(`wrote ${outFile}: ${names.join(', ')}`);
